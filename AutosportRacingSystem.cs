        public static void GenerateRouteInfo()
        {
            Log(LogImportance.Info, "Generating route info...");
            _trackPoints.Clear();
            _cornerPoints.Clear();
            _nodeLaneOffsets.Clear();


            
            while (_trackPoints.Count() < _routeNodes.Count())
            {
                TrackPoint t = new TrackPoint();
                t.Node = _trackPoints.Count();
                t.Position = _routeNodes[t.Node];

                CornerPoint c = new CornerPoint();
                c.Node = _trackPoints.Count();

                _trackPoints.Add(t);
                _cornerPoints.Add(c);

            }


            
            foreach (TrackPoint t in _trackPoints)
            {
                int Average = (int)(t.TrackHalfWidth * 2);
                if (t.Node > 50 && t.Node < _routeNodes.Count - 50)
                {

                    Vector3 l = (_routeNodes[t.Node] - _routeNodes[t.Node - Average]).Normalized;
                    Vector3 f = (_routeNodes[t.Node + Average] - _routeNodes[t.Node]).Normalized;

                    t.Direction = (_routeNodes[t.Node + 2] - _routeNodes[t.Node - 2]).Normalized;

                    t.Elevation = (_routeNodes[t.Node + 10] - _routeNodes[t.Node - 10]).Normalized.Z * 90f;

                    

                    l = (_routeNodes[t.Node] - _routeNodes[t.Node - Average]).Normalized;
                    f = (_routeNodes[t.Node + Average] - _routeNodes[t.Node]).Normalized;

                    l.Z = 0f;
                    f.Z = 0f;

                    float Angle = Vector3.SignedAngle(l, f, Vector3.WorldUp);
                    if (float.IsNaN(Angle) || float.IsInfinity(Angle)) Angle = 0;
                    t.Angle = Angle;

                    int LongAF = 10;
                    int PreciseAF = 4;

                    t.GeneralCurveRadius = Circumradius3D(_routeNodes[t.Node - LongAF], _routeNodes[t.Node + LongAF], _routeNodes[t.Node]); 
                    t.PreciseCurveRadius = Circumradius3D(_routeNodes[t.Node - PreciseAF], _routeNodes[t.Node + PreciseAF], _routeNodes[t.Node]); 

                }
                else
                {
                    t.Angle = 0f;
                    t.Direction = (_routeNodes[10] - _routeNodes[5]).Normalized;
                    t.Elevation = 0f;
                }

                if (ARS._nodeHalfWidths.ContainsKey(t.Node)) t.TrackHalfWidth = ARS._nodeHalfWidths[t.Node];
            }

            
            foreach (CornerPoint c in _cornerPoints)
            {
                int Average = 20;

                if (c.Node > Average && c.Node < _routeNodes.Count - Average)
                {
                    Vector3 pre = _trackPoints[c.Node - Average].Direction;
                    Vector3 fut = _trackPoints[c.Node + Average].Direction;
                    c.Angle = Vector3.SignedAngle(pre, fut, Vector3.WorldUp);
                    c.ElevationChange = ((fut - pre).Z * 90);
                    c.Elevation = _trackPoints[c.Node].Elevation;
                }
                else
                {
                    c.Angle = 0f;
                    c.Elevation = 0f;
                    c.ElevationChange = 0f;
                }

                c.LengthStart = 20;
                c.LengthEnd = 20;
            }


            for (int i = 20; i < _cornerPoints.Count - 20; i++)
            {
                float Radius = _cornerPoints[i].GetRadius();
                if (Radius < 90)
                {
                    if (_cornerPoints[i - 5].GetRadius() > Radius && Radius < _cornerPoints[i + 5].GetRadius())
                    {
                        _cornerPoints[i].IsKey = true;
                        i += 20;
                    }
                }
            }

            
            var keyCorners = _cornerPoints.Where(co => co.IsKey).OrderBy(co => co.Node).ToList();

            const int minSpan = 5;
            const int maxSpanSearch = 300;
            const float radiusFactorForCornerBounds = 50;

            
            foreach (CornerPoint c in keyCorners)
            {
                float radius = GetPreciseRadius(_trackPoints[c.Node], 3);
                radius = Clamp(radius, 5f, 9999f);
                float thresholdRadius = radius * radiusFactorForCornerBounds;

                int startCandidates = Math.Max(10, c.Node - maxSpanSearch);
                int endCandidates = Math.Min(_trackPoints.Count - 11, c.Node + maxSpanSearch);

                int foundStartNode = startCandidates;
                for (int nodeID = c.Node - 1; nodeID >= startCandidates; nodeID--)
                {
                    if (_trackPoints[nodeID].PreciseCurveRadius >= thresholdRadius)
                    {
                        foundStartNode = nodeID;
                        break;
                    }
                }

                c.LengthStart = Math.Max(minSpan, c.Node - foundStartNode);
                c.LengthEnd = c.LengthStart;

                int maxSpanFromTrackWide = Math.Max(minSpan, (int)Math.Round(_trackPoints[c.Node].TrackHalfWidth * 4f));
                c.LengthStart = Math.Min(c.LengthStart, maxSpanFromTrackWide);
                c.LengthEnd = Math.Min(c.LengthEnd, maxSpanFromTrackWide);

                // Store the minimum precise curve radius across the final corner span
                int radiusStart = (int)Clamp(c.Node - c.LengthStart, 0, _trackPoints.Count - 1);
                int radiusEnd = (int)Clamp(c.Node + c.LengthEnd, 0, _trackPoints.Count - 1);
                float minRadius = float.MaxValue;
                for (int n = radiusStart; n <= radiusEnd; n++)
                {
                    float rN = _trackPoints[n].PreciseCurveRadius;
                    if (rN > 0f && rN < minRadius) minRadius = rN;
                }
                c.Radius = (minRadius == float.MaxValue) ? c.GetPreciseRadius() : minRadius;
            }

            // Second pass: disable any key corner that's too close to the corner behind it.
            // Separation scales with track width — full width (2× half-width) × 10, so a 16 m
            // wide track demands corners at least 160 m apart. Uses the wider of the two corners.
            for (int i = 1; i < keyCorners.Count;)
            {
                CornerPoint prev = keyCorners[i - 1];
                CornerPoint curr = keyCorners[i];

                float pairHalfWidth = Math.Max(_trackPoints[prev.Node].TrackHalfWidth, _trackPoints[curr.Node].TrackHalfWidth);
                int minCornerSeparationNodes = (int)(pairHalfWidth * 20f);

                if (curr.Node - prev.Node < minCornerSeparationNodes)
                {
                    curr.IsKey = false;
                    keyCorners.RemoveAt(i);
                    continue;
                }

                i++;
            }

            
            foreach (CornerPoint c in keyCorners)
            {
                int cornerSign = Math.Sign(c.Angle);
                if (cornerSign == 0) continue;

                int startNode = (int)Clamp(c.Node - c.LengthStart, 0, _trackPoints.Count - 1);
                int endNode = (int)Clamp(c.Node + c.LengthEnd, 0, _trackPoints.Count - 1);
                if (endNode < startNode) continue;

                
                
                TrackPoint startTrackPoint = _trackPoints[startNode];
                TrackPoint apexTrackPoint = _trackPoints[c.Node];
                TrackPoint endTrackPoint = _trackPoints[endNode];

                const float outsideAnchorFactor = 0.9f;
                int bezierSamples = Math.Max(24, (endNode - startNode) * 3);
                float apexAnchorFactor = 5f;
                const int maxApexSolveTries = 300;
                const float apexTargetTolerance = 0.1f;
                const float apexAdjustGain = 0.8f;
                const float maxFactorDeltaPerTry = 0.08f;
                const float minApexAnchorFactor = -5f;
                const float maxApexAnchorFactor = 5f;
                const float apexSearchWindow = 0.2f;
                const float apexProjectedClampFactor = 3f;

                Vector3 apexRight = Vector3.Cross(Vector3.WorldUp, apexTrackPoint.Direction);
                bool canSolveApex = apexRight.LengthSquared() > 0.0001f;
                if (canSolveApex) apexRight.Normalize();

                List<Vector3> bezierPoints = null;
                for (int attempt = 0; attempt < maxApexSolveTries; attempt++)
                {
                    float startOutsideOffset = cornerSign * startTrackPoint.TrackHalfWidth * outsideAnchorFactor;
                    float apexInsideOffset = -cornerSign * apexTrackPoint.TrackHalfWidth * apexAnchorFactor;
                    float endOutsideOffset = cornerSign * endTrackPoint.TrackHalfWidth * outsideAnchorFactor;

                    Vector3 bezierStart = startTrackPoint.Position - (Vector3.Cross(Vector3.WorldUp, startTrackPoint.Direction) * startOutsideOffset);
                    Vector3 bezierControl = apexTrackPoint.Position - (Vector3.Cross(Vector3.WorldUp, apexTrackPoint.Direction) * apexInsideOffset);
                    Vector3 bezierEnd = endTrackPoint.Position - (Vector3.Cross(Vector3.WorldUp, endTrackPoint.Direction) * endOutsideOffset);

                    bezierPoints = new List<Vector3>(bezierSamples + 1);
                    for (int s = 0; s <= bezierSamples; s++)
                    {
                        float t = (float)s / bezierSamples;
                        bezierPoints.Add(QuadraticBezier(bezierStart, bezierControl, bezierEnd, t));
                    }

                    if (!canSolveApex) break;

                    Vector3 apexPos = apexTrackPoint.Position;
                    int apexSampleIndex = bezierSamples / 2;
                    int windowHalf = Math.Max(2, (int)(bezierSamples * apexSearchWindow * 0.5f));
                    int sampleStart = Math.Max(0, apexSampleIndex - windowHalf);
                    int sampleEnd = Math.Min(bezierSamples, apexSampleIndex + windowHalf);

                    Vector3 closestAtApex = bezierPoints[sampleStart];
                    float bestApexDistSq = (closestAtApex - apexPos).LengthSquared();
                    for (int i = sampleStart + 1; i <= sampleEnd; i++)
                    {
                        float distSq = (bezierPoints[i] - apexPos).LengthSquared();
                        if (distSq < bestApexDistSq)
                        {
                            bestApexDistSq = distSq;
                            closestAtApex = bezierPoints[i];
                        }
                    }

                    float apexProjectedOffset = Vector3.Dot(apexPos - closestAtApex, apexRight);
                    float apexProjectedBound = Math.Max(0.001f, apexTrackPoint.TrackHalfWidth * apexProjectedClampFactor);
                    float apexProjectedOffsetForError = Clamp(apexProjectedOffset, -apexProjectedBound, apexProjectedBound);
                    float apexTargetOffset = -cornerSign * apexTrackPoint.TrackHalfWidth;
                    float insideSign = Math.Sign(apexTargetOffset);
                    if (insideSign == 0f) insideSign = 1f;
                    float apexProjectedInsideAxis = apexProjectedOffsetForError * insideSign;
                    float apexTargetInsideAxis = Math.Abs(apexTargetOffset);
                    float apexError = apexTargetInsideAxis - apexProjectedInsideAxis;
                    if (Math.Abs(apexError) <= apexTargetTolerance) break;

                    float normalizedError = apexError / Math.Max(0.001f, apexTrackPoint.TrackHalfWidth);
                    float factorDelta = Clamp(Math.Abs(normalizedError) * apexAdjustGain, 0f, maxFactorDeltaPerTry);
                    apexAnchorFactor = Clamp(apexAnchorFactor - factorDelta, minApexAnchorFactor, maxApexAnchorFactor);
                }

                
                
                for (int node = startNode; node <= endNode; node++)
                {
                    TrackPoint tNode = _trackPoints[node];
                    Vector3 nodePos = tNode.Position;

                    Vector3 closestBezier = bezierPoints[0];
                    float bestDistSq = (closestBezier - nodePos).LengthSquared();
                    for (int i = 1; i < bezierPoints.Count; i++)
                    {
                        float distSq = (bezierPoints[i] - nodePos).LengthSquared();
                        if (distSq < bestDistSq)
                        {
                            bestDistSq = distSq;
                            closestBezier = bezierPoints[i];
                        }
                    }

                    Vector3 trackRight = Vector3.Cross(Vector3.WorldUp, tNode.Direction);
                    if (trackRight.LengthSquared() < 0.0001f)
                    {
                        _nodeLaneOffsets[node] = 0f;
                        continue;
                    }

                    trackRight.Normalize();
                    float offset = Vector3.Dot(nodePos - closestBezier, trackRight);
                    _nodeLaneOffsets[node] = offset;
                }
            }

            Log(LogImportance.Info, "Route generated");

            CornerPoint corner = _cornerPoints.FirstOrDefault(co => co.IsKey);
            foreach (Racer r in ARS._racers) r.Brain.Corner = new Corner(CornerApexSpeed(corner, r), corner);
        }

        public static float Circumradius3D(Vector3 a, Vector3 b, Vector3 midpoint)
        {
            Vector2 a2 = new Vector2(a.X, a.Y);
            Vector2 b2 = new Vector2(b.X, b.Y);
            Vector2 midpoint2 = new Vector2(midpoint.X, midpoint.Y);

            return Circumradius2D(a2, b2, midpoint2);
        }
        public static float Circumradius2D(Vector2 a, Vector2 b, Vector2 midPoint)
        {
            Vector2 point1 = a;
            Vector2 point2 = b;
            Vector2 point3 = midPoint;

            Vector2 midpoint1 = (point1 + point2) / 2;
            float dx1 = point2.X - point1.X;
            float slope1 = dx1 != 0f ? (point2.Y - point1.Y) / dx1 : float.PositiveInfinity;

            float perpendicularSlope1 = slope1 != 0f ? -1 / slope1 : float.PositiveInfinity;

            Vector2 midpoint2 = (point2 + point3) / 2;
            float dx2 = point3.X - point2.X;
            float slope2 = dx2 != 0f ? (point3.Y - point2.Y) / dx2 : float.PositiveInfinity;

            float perpendicularSlope2 = slope2 != 0f ? -1 / slope2 : float.PositiveInfinity;

            float denom = perpendicularSlope2 - perpendicularSlope1;
            if (denom == 0f || float.IsNaN(denom) || float.IsInfinity(denom)) return 999f;

            float centerX = (midpoint1.Y - midpoint2.Y + perpendicularSlope2 * midpoint2.X - perpendicularSlope1 * midpoint1.X) / denom;
            float centerY = midpoint1.Y + perpendicularSlope1 * (centerX - midpoint1.X);

            float radius = Vector2.Distance(new Vector2(centerX, centerY), point1);
            if (float.IsNaN(radius) || float.IsInfinity(radius)) return 999f;

            return radius;
        }

        public static float GetPreciseRadius(TrackPoint trackPoint, int span)
        {
            if (trackPoint == null || _trackPoints == null || _trackPoints.Count < 3) return 999f;

            int safeSpan = Math.Max(1, span);
            int node = (int)Clamp(trackPoint.Node, 0, _trackPoints.Count - 1);
            int minSafeNode = safeSpan;
            int maxSafeNode = _trackPoints.Count - 1 - safeSpan;
            if (node < minSafeNode || node > maxSafeNode) return trackPoint.PreciseCurveRadius;

            Vector3 prev = _trackPoints[node - safeSpan].Position;
            Vector3 next = _trackPoints[node + safeSpan].Position;
            Vector3 mid = _trackPoints[node].Position;

            float r = Circumradius3D(prev, next, mid);
            if (float.IsNaN(r) || float.IsInfinity(r) || r <= 0f) return trackPoint.PreciseCurveRadius;
            return r;
        }

        
        
        
        
        public static float HillGripDeltaGs(Vector3 start, Vector3 midpoint, Vector3 end, float velocity)
        {
            if (velocity <= 0f) return 0f;

            
            float s0 = 0f;
            float s1 = Vector2.Distance(new Vector2(start.X, start.Y), new Vector2(midpoint.X, midpoint.Y));
            float s2 = s1 + Vector2.Distance(new Vector2(midpoint.X, midpoint.Y), new Vector2(end.X, end.Y));

            if (s1 <= 0.001f || s2 <= s1 + 0.001f) return 0f;

            Vector2 p0 = new Vector2(s0, start.Z);
            Vector2 p1 = new Vector2(s1, midpoint.Z);
            Vector2 p2 = new Vector2(s2, end.Z);

            
            Vector2 ab = p1 - p0;
            Vector2 bc = p2 - p1;
            Vector2 ac = p2 - p0;

            float abLen = ab.Length();
            float bcLen = bc.Length();
            float acLen = ac.Length();
            if (abLen < 0.001f || bcLen < 0.001f || acLen < 0.001f) return 0f;

            float cross = (ab.X * ac.Y) - (ab.Y * ac.X);
            float curvature = (2f * cross) / (abLen * bcLen * acLen);
            if (Math.Abs(curvature) < 0.00001f) return 0f;

            const float gravity = 9.8f;
            float deltaGs = ((velocity * velocity) * curvature) / gravity;

            if (float.IsNaN(deltaGs) || float.IsInfinity(deltaGs)) return 0f;
            return deltaGs;
        }

        
        
        
        
        public static float GetHillGsLossAtCurrentTrackPoint(Racer r)
        {
            if (r == null || !CanWeUse(r.Car) || _trackPoints.Count < 2) return 0f;

            int node = (int)Clamp(r.CurrentTrackPoint.Node, 0, _trackPoints.Count - 1);
            int forwardOffset = (int)Clamp((int)(Math.Max(r.Car.Velocity.Length(), 5f) * 0.5f), 1, 50);
            int aheadNode = node + forwardOffset;
            if (aheadNode >= _trackPoints.Count) aheadNode -= _trackPoints.Count;

            Vector3 from = _trackPoints[node].Position;
            Vector3 to = _trackPoints[aheadNode].Position;

            float horizontalDistance = Vector2.Distance(new Vector2(from.X, from.Y), new Vector2(to.X, to.Y));
            if (horizontalDistance <= 0.001f) return 0f;

            float climbAngleRad = (float)Math.Atan2(to.Z - from.Z, horizontalDistance);
            if (Math.Abs(climbAngleRad) <= 0.0001f) return 0f;

            float gravityScale = r.Handling.Gravity / 9.8f;
            float lossGs = (float)Math.Abs(Math.Sin(climbAngleRad)) * gravityScale;

            if (float.IsNaN(lossGs) || float.IsInfinity(lossGs)) return 0f;
            return Clamp(lossGs, 0f, 2f);
        }

        
        
        
        
