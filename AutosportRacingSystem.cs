        public static void FindNextCorner(Racer r)
        {
            // Don't advance past the current corner until we've passed its apex.
            // The corner speed cap must remain active through the apex.
            if (r.Brain.Corner != null && r.CurrentTrackPoint.Node <= r.Brain.Corner.Point.Node)
                return;

            CornerPoint nextCorner = GetNextCorner(r.CurrentTrackPoint.Node);
            if (nextCorner == null)
            {
                r.Brain.Corner = null;
                return;
            }

            if (r.Brain.Corner == null || r.Brain.Corner.Point != nextCorner)
                r.Brain.Corner = new Corner(CornerApexSpeed(nextCorner, r), nextCorner);
        }

        public static CornerPoint GetNextCorner(int currentNode)
        {
            CornerPoint firstCorner = null;
            foreach (CornerPoint corner in _cornerPoints)
            {
                if (!corner.IsKey) continue;
                if (firstCorner == null) firstCorner = corner;
                if (corner.Node > currentNode) return corner;
            }

            return _isPointToPoint ? null : firstCorner;
        }

        
        
        

        
        
        
        const float BrakingCoastSecondsBeforeApex = 2f; // reach corner speed this many seconds before the apex

        public static float MaxSpeedForBrakingDistance(CornerPoint c, Racer r)
        {
            
            int apexNode = c.Node;
            if (!_isPointToPoint && apexNode < 0) apexNode += _trackPoints.Count;
            float velTarget = r.Brain.Corner.Speed;
            // Reserve corner-speed × N seconds of distance so the car reaches corner speed
            // N seconds before the apex, then coasts the rest at corner speed.
            // TEMPORARILY DISABLED — cars were braking too soon. Brake to the apex itself.
            // float coastReserve = velTarget * BrakingCoastSecondsBeforeApex;
            float rawDistance = apexNode - r.CurrentTrackPoint.Node;
            if (!_isPointToPoint && rawDistance < 0f) rawDistance += _trackPoints.Count;
            if (rawDistance < 0f) rawDistance = 0f;
            // Divebomb: halve the braking distance so the car brakes later and carries
            // more entry speed into the corner — the whole point of the maneuver.
            float distance = r.ActiveManeuver.Type == ManeuverType.DiveBomb
                ? rawDistance * 0.5f
                : rawDistance;
            if (distance < 0f) distance = 0f;

            float brakingAbility = Math.Min(r.Handling.BrakingAbility * 4, r.VehicleData.CurrentMechanicalGrip);
            
            float decel = brakingAbility * r.Handling.Gravity;
            // Yielding cars perceive half the deceleration, so they brake earlier.
            if (r.ActiveManeuver.Type == ManeuverType.Yield)
                decel *= 0.5f;

            float spd = (float)Math.Sqrt(velTarget * velTarget + 2f * decel * distance);
            if (float.IsNaN(spd) || float.IsInfinity(spd)) spd = 999f;
            return spd;
        }

        

