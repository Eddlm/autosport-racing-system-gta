                {
                    vehicleModel = new Model(modelName);
                }
                else
                {
                    int hashVehicleModel = 0;
                    int.TryParse(modelName, out hashVehicleModel);
                    vehicleModel = hashVehicleModel;
                }

                int loadTries = 0;
                while (!vehicleModel.IsLoaded && loadTries < 500)
