        void PlaceCars(bool sortbypower)
        {
            if (sortbypower)
            {

                GridSort sort = GridSort.Power;
                foreach (GridSort g in Enum.GetValues(typeof(GridSort)))
                {
                    g.ToString().ToLowerInvariant().Contains(DevSettingsFile.GetValue<string>("RACERS", "GridSorting", "Power").ToLowerInvariant());
                    sort = g;
                }

                switch (sort)
                {
                    case GridSort.Power: { _racers = _racers.OrderBy(v => Function.Call<float>(Hash.GET_VEHICLE_ACCELERATION, v.Car)).ToList(); break; }
                    case GridSort.PowerDescendent: { _racers = _racers.OrderBy(v => Function.Call<float>(Hash.GET_VEHICLE_ACCELERATION, v.Car)).Reverse().ToList(); break; }
                    case GridSort.EstimatedTopSpeed: { _racers = _racers.OrderBy(v => Function.Call<float>((Hash)0xF417C2502FFFED43, v.Car.Model.Hash)).ToList(); break; }
                    case GridSort.EstimatedTopSpeedDescendent: { _racers = _racers.OrderBy(v => Function.Call<float>((Hash)0xF417C2502FFFED43, v.Car.Model.Hash)).Reverse().ToList(); break; }
                    case GridSort.Random: { _racers = _racers.OrderBy(v => v.Car.Model.Hash.ToString().Substring(0, 1) + (int)v.Car.PrimaryColor).ToList(); break; }
                }

            }
            if (_racers.Any(r => r.TeamRole == Team.Cop))
            {
                UI.Notify("Cops 'n' Crooks detected");
                _racers = _racers.OrderBy(v => (int)v.TeamRole).ToList();
            }

            Racer p = null;
            int index = 0;
            foreach (Racer r in _racers) if (r.Driver.IsPlayer)
            {
                index = _racers.IndexOf(r);
                p = r;
            }
            if (p != null)
            {

                _racers.RemoveAt(index);
                _racers.Add(p);
            }



            if (_isPointToPoint) { _gridPositions.Reverse(); }
            int pos = 0;
            foreach (Racer r in _racers)
            {
                r.Initialize();

                r.Car.Position = _gridPositions[pos];
                if (_isPointToPoint)
                {
                    r.Car.Heading = (_routeNodes[2] - _routeNodes[0]).ToHeading();
                }
                else
                {
                    if (pos > _gridPositions.Count - 2)
                    {
                        r.Car.Heading = (_gridPositions[pos - 2] - _gridPositions[pos]).Normalized.ToHeading();
                    }
                    else
                    {
                        r.Car.Heading = (_gridPositions[pos] - _gridPositions[pos + 2]).Normalized.ToHeading();
                    }
                }

                





                pos++;
            }
        }

