	public static float LaneApproach(float DistPercent)
	{
		float result = 0f;
		if (DistPercent >= 80f)
		{
			result = map(DistPercent, 80f, 100f, 95f, 100f, clamp: true);
		}
		else if (DistPercent >= 60f)
		{
			result = map(DistPercent, 60f, 80f, 80f, 95f, clamp: true);
		}
		else if (DistPercent >= 40f)
		{
			result = map(DistPercent, 40f, 60f, 50f, 80f, clamp: true);
		}
		else if (DistPercent >= 20f)
		{
			result = map(DistPercent, 20f, 40f, 25f, 50f, clamp: true);
		}
		else if (DistPercent >= 0f)
		{
			result = map(DistPercent, 0f, 20f, 0f, 25f, clamp: true);
		}
		return result;
	}

	public void FillKnownTracks(bool allowScriptYield = true)
	{
		TrackTags.Clear();
		ImmersiveJoins.Clear();
		Log(LogImportance.Info, "Learning available tracks...");
		List<string> list = Directory.GetDirectories("scripts\\ARS\\Tracks").ToList();
		list.Add("scripts\\ARS\\Tracks");
		foreach (string item in list)
		{
			int num = 0;
			foreach (string item2 in Directory.EnumerateFiles(item))
			{
				string fileName = System.IO.Path.GetFileName(item2);
				Log(LogImportance.Info, item2 + " - [" + string.Join(", ", GetTrackTags(item2)) + "]");
				TrackTags.Add(item2, string.Join(", ", GetTrackTags(item2)));
				if (!ImmersiveJoins.ContainsKey(GetTrackStartPos(item2)))
				{
					ImmersiveJoins.Add(GetTrackStartPos(item2), item2);
				}
				num++;
				if (allowScriptYield && num > 5)
				{
					DisplayHelpTextTimed("Loading " + fileName, 5000);
					num = 0;
					Script.Yield();
				}
			}
		}
		KnownTracks = Directory.GetFiles("scripts\\ARS\\Tracks").ToList();
		Log(LogImportance.Info, "Done.");
		Log(LogImportance.Info, "-------------");
	}

