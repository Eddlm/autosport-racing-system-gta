	public void StartLoadScript()
	{
		if (!IsLoadingScript)
		{
			DisplayHelpTextTimed("Loading ~b~ARS.~w~ May take a while.", 20000);
			Loaded = false;
			IsLoadingScript = true;
			LoadScriptTask = Task.Run(delegate
			{
				FillKnownDisciplines(allowScriptYield: false);
				FillKnownTracks(allowScriptYield: false);
				ReFilterKnownTracks(TrackFilter);
			});
		}
	}

	private void HandleLoadScriptTask()
	{
		if (IsLoadingScript && LoadScriptTask != null && LoadScriptTask.IsCompleted)
		{
			if (LoadScriptTask.IsFaulted)
			{
				Loaded = false;
				Exception ex = LoadScriptTask.Exception?.GetBaseException();
				Log(LogImportance.Error, "Initialization failed: " + ((ex != null) ? ex.Message : "Unknown error"), forced: true);
				DisplayHelpTextTimed("~r~ARS failed to load. Check log.", 4000);
			}
			else
			{
				FillCachedCandidates(DisciplineFilter, intendedOpponents);
				Log(LogImportance.Info, "Initialization complete.", forced: true);
				DisplayHelpTextTimed("~g~ARS has loaded.", 2000);
				HelpMessages.Add("Press ~INPUT_SPRINT~ + ~INPUT_CONTEXT~ to open the ~b~ARSe~w~ menu.");
				Loaded = true;
			}
			IsLoadingScript = false;
			LoadScriptTask = null;
		}
	}

