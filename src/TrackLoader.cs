        public static void LoadTrack(ARS ars, XmlDocument xmlFile)
        {
            ARS.Log(ARS.LogImportance.Info, "Loading track");
            if (xmlFile == null)
            {
                UI.Notify("~r~Invalid track file.");
                return;
            }
            if (!ars.IsFreeCamActive) Function.Call(Hash.DO_SCREEN_FADE_OUT, 200);
            ars.SetLoadingPromptText("Loading track...");
            Script.Wait(500);

            ARS.CurrentFile = xmlFile;
            foreach (Prop p in ARS.CustomProps) if (ARS.CanWeUse(p)) p.Delete();
            foreach (Prop p in ARS.AutoGeneratedProps) if (ARS.CanWeUse(p)) p.Delete();
            foreach (Prop p in ARS.StartLineFlares) if (ARS.CanWeUse(p)) p.Delete();
            ARS.RouteNodes.Clear();
            ARS.NodeHalfWidths.Clear();
            ARS.StartLineFlares.Clear();
            QueuedFlares.Clear();

            XmlNode r = xmlFile.SelectSingleNode("Data");

            Thread.CurrentThread.CurrentCulture = CultureInfo.GetCultureInfo("en-US");

            foreach (XmlElement prop in r.SelectNodes("Objects/Prop"))
            {
                string x = "0";
                string y = "0";
                string z = "0";
                if (ARS.NodeExists(prop, "X") && ARS.NodeExists(prop, "Y") && ARS.NodeExists(prop, "Z"))
                {
                    x = prop.SelectSingleNode("X").InnerText;
                    y = prop.SelectSingleNode("Y").InnerText;
                    z = prop.SelectSingleNode("Z").InnerText;
                }

                bool isDynamic = false;

                if (ARS.NodeExists(prop, "IsDynamic")) bool.TryParse(prop.SelectSingleNode("IsDynamic").InnerText, out isDynamic);

                float fx = 0f;
                float.TryParse(x, out fx);
                float fy = 0f;
                float.TryParse(y, out fy);
                float fz = 0f;
                float.TryParse(z, out fz);
                Vector3 pos = new Vector3(fx, fy, fz);
                if (ARS.NodeExists(prop, "RotX") && ARS.NodeExists(prop, "RotY") && ARS.NodeExists(prop, "RotZ"))
                {
                    x = prop.SelectSingleNode("RotX").InnerText;
                    y = prop.SelectSingleNode("RotY").InnerText;
                    z = prop.SelectSingleNode("RotZ").InnerText;
                }
                fx = 0f;
                float.TryParse(x, out fx);
                fy = 0f;
                float.TryParse(y, out fy);
                fz = 0f;
                float.TryParse(z, out fz);
                Vector3 rot = new Vector3(fx, fy, fz);

                if (ARS.NodeExists(prop, "Model"))
                {
                    int hash = 0;
                    int.TryParse(prop.SelectSingleNode("Model").InnerText, out hash);
                    if (hash != 0 && new Model(hash).IsValid)
                    {
                        Prop myprop = World.CreateProp(hash, pos, rot, false, false);
                        myprop.Position = pos;
                        Function.Call(Hash.SET_ENTITY_DYNAMIC, myprop, isDynamic);
                        Function.Call(Hash.FREEZE_ENTITY_POSITION, myprop, !isDynamic);
                        Function.Call(Hash.SET_OBJECT_PHYSICS_PARAMS, myprop, 200f * myprop.Model.GetDimensions().Length(), 1f);

                        if (prop.SelectSingleNode("TextureVariation") != null) Function.Call(Hash._0x971DA0055324D033, myprop, int.Parse(prop.SelectSingleNode("TextureVariation").InnerText));

                        ARS.CustomProps.Add(myprop);
                    }
                }
            }
            List<XmlElement> routeNodes = new List<XmlElement>();
            foreach (XmlElement e in r.SelectNodes("Route/Point")) routeNodes.Add(e);

            if (ARS.DebugToggles[Options.ReverseRoute])
            {
                routeNodes.Reverse();
            }

            int i = 0;
            float W = 5;
            float oldW = 0;
            foreach (XmlElement e in routeNodes)
            {
                string x = e.SelectSingleNode("X").InnerText;
                string y = e.SelectSingleNode("Y").InnerText;
                string z = e.SelectSingleNode("Z").InnerText;

                float fx = 0f;
                float.TryParse(x, out fx);
                float fy = 0f;
                float.TryParse(y, out fy);
                float fz = 0f;
                float.TryParse(z, out fz);
                Vector3 pos = new Vector3(fx, fy, fz);

                float.TryParse(e.SelectSingleNode("Wide").InnerText, out W);

                if (ARS.RouteNodes.Count > 5) W = ARS.Clamp(W, oldW - 0.25f, oldW + 0.25f);

                ARS.RouteNodes.Add(pos);
                ARS.NodeHalfWidths.Add(i, W);
                oldW = W;
                i++;
            }

            // Detect circuit vs point-to-point BEFORE GenerateRouteInfo so the geometry pass and BuildApexTable can
            // wrap node indices across the start/finish seam; without it, a corner sitting on the finish line is
            // invisible to the apex table on circuits.
            RefreshRouteTopology();

            GenerateRouteInfo();

            Script.Wait(1000);
            ARS.Log(ARS.LogImportance.Info, "Loading props");
            ars.SetLoadingPromptText("Loading props...");
            BuildTrackLimits(ARS.RouteNodes, ARS.NodeHalfWidths, ARS.CurrentFile, ref ARS.IsPointToPoint, ARS.StartLineFlares);

            if (ARS.CanWeUse(Game.Player.Character.CurrentVehicle))
            {
                Game.Player.Character.CurrentVehicle.Position = ARS.RouteNodes[0];
            }
            else
            {
                Vector3 pos = ARS.RouteNodes[2];
                Vector3 dir = ARS.RouteNodes[3] - ARS.RouteNodes[1];
                dir.Z = 0f;
                if (dir.LengthSquared() < 0.001f) dir = Vector3.WorldNorth;
                dir.Normalize();
                Vector3 right = Vector3.Cross(dir, Vector3.WorldUp);
                float halfWide = ARS.NodeHalfWidths.ContainsKey(2) ? ARS.NodeHalfWidths[2] : 5f;
                float side = ARS.GetRandomInt(0, 2) == 0 ? 1f : -1f;
                Game.Player.Character.Position = pos + right * (halfWide * side) + new Vector3(0f, 0f, 0.5f);
            }
            if (ARS.CanWeUse(ARS.FreeCamRide)) ARS.FreeCamRide.Position = ARS.RouteNodes[5] + new Vector3(0, 0, 20);
            ars.SetLoadingPromptText("Finished loading props");
            Function.Call(Hash._0x10D373323E5B9C0D);
            ars.SetSPLVisibility(false);

            ARS.Log(ARS.LogImportance.Info, "Loaded track");
        }

        public static void GenerateRouteInfo()
        {
            ARS.Log(ARS.LogImportance.Info, "Generating route info...");
            ARS.TrackPoints.Clear();
            while (ARS.TrackPoints.Count < ARS.RouteNodes.Count)
            {
                int node = ARS.TrackPoints.Count;
                ARS.TrackPoints.Add(new TrackPoint { Node = node, Position = ARS.RouteNodes[node] });
            }

            RecomputeCumulativeDistances();

            int nodeCount = ARS.RouteNodes.Count;
            foreach (TrackPoint point in ARS.TrackPoints) ComputePointGeometry(point, nodeCount);

            BuildApexTable();
            ARS.Log(ARS.LogImportance.Info, "Route generated");
        }

        // One node's plan-view geometry, shared by the load pass and the creator's incremental rebuild so the two
        // cannot disagree. The angle window is a flat ten nodes: it used to read TrackHalfWidth, which on a full pass
        // is still the fresh object's default because the width is written *below* this call, so the read only ever
        // saw ten — an incremental pass over already-written points would have widened it silently.
        const int GeometryWindowNodes = 10;
        // The point-to-point end band, where a node has no usable window. Its boundary is the route count minus this,
        // so an append or a delete anywhere moves it — the band is invalidated as a whole by any change.
        const int PointToPointEndBandNodes = 50;

        static void ComputePointGeometry(TrackPoint point, int nodeCount)
        {
            int average = GeometryWindowNodes;
            bool canCompute = ARS.IsPointToPoint
                ? nodeCount > PointToPointEndBandNodes && point.Node > PointToPointEndBandNodes && point.Node < nodeCount - PointToPointEndBandNodes
                : point.Node >= 0 && point.Node < nodeCount;

            if (canCompute)
            {
                Vector3 left = (ARS.RouteNodes[point.Node] - ARS.RouteNodes[Wrap(point.Node - average, nodeCount)]).Normalized;
                Vector3 forward = (ARS.RouteNodes[Wrap(point.Node + average, nodeCount)] - ARS.RouteNodes[point.Node]).Normalized;
                point.Direction = (ARS.RouteNodes[Wrap(point.Node + 2, nodeCount)] - ARS.RouteNodes[Wrap(point.Node - 2, nodeCount)]).Normalized;
                point.Elevation = (ARS.RouteNodes[Wrap(point.Node + 3, nodeCount)] - ARS.RouteNodes[Wrap(point.Node - 3, nodeCount)]).Normalized.Z * 90f;
                left.Z = 0f;
                forward.Z = 0f;
                point.Angle = Vector3.SignedAngle(left, forward, Vector3.WorldUp);
                if (float.IsNaN(point.Angle) || float.IsInfinity(point.Angle)) point.Angle = 0f;
                point.GeneralCurveRadius = Circumradius3D(ARS.RouteNodes[Wrap(point.Node - 10, nodeCount)], ARS.RouteNodes[Wrap(point.Node + 10, nodeCount)], ARS.RouteNodes[point.Node]);
                point.PreciseCurveRadius = Circumradius3D(ARS.RouteNodes[Wrap(point.Node - 4, nodeCount)], ARS.RouteNodes[Wrap(point.Node + 4, nodeCount)], ARS.RouteNodes[point.Node]);
                point.ExactRadius = Circumradius3D(ARS.RouteNodes[Wrap(point.Node - 2, nodeCount)], ARS.RouteNodes[Wrap(point.Node + 2, nodeCount)], ARS.RouteNodes[point.Node]);
            }
            else
            {
                // The point-to-point end band has no usable window, and a rebuilt point would otherwise keep the
                // previous pass's radii: SmoothedRadius skips 999, so a stale value below it would read as curvature.
                point.Angle = 0f;
                point.Direction = nodeCount > 10 ? (ARS.RouteNodes[10] - ARS.RouteNodes[5]).Normalized : Vector3.Zero;
                point.Elevation = 0f;
                point.GeneralCurveRadius = 999f;
                point.PreciseCurveRadius = 999f;
                point.ExactRadius = 999f;
            }

            if (ARS.NodeHalfWidths.ContainsKey(point.Node)) point.TrackHalfWidth = ARS.NodeHalfWidths[point.Node];
        }

        static void RecomputeCumulativeDistances()
        {
            float cumulative = 0f;
            for (int i = 0; i < ARS.TrackPoints.Count; i++)
            {
                ARS.TrackPoints[i].CumulativeDistance = cumulative;
                int next = (i + 1) % ARS.TrackPoints.Count;
                cumulative += ARS.TrackPoints[i].Position.DistanceTo(ARS.TrackPoints[next].Position);
            }
            ARS.RouteLengthMeters = cumulative;
        }

        // Topology belongs to the route, not to the load: the last node within 20 m of the first closes the circuit.
        // It has to be recomputed wherever the route changes, or a session inherits the flag from the last track it
        // loaded, and every node window, the seam and the corner scan then run under the wrong assumption.
        public static void RefreshRouteTopology()
        {
            ARS.IsPointToPoint = ARS.RouteNodes.Count > 1 && ARS.RouteNodes[0].DistanceTo(ARS.RouteNodes[ARS.RouteNodes.Count - 1]) > 20f;
        }

        // The derived table of a route that no longer exists. The creator clears it on entry, or the first apply
        // would rebuild against the previous track's points and corners.
        public static void ClearRouteInfo()
        {
            ARS.TrackPoints.Clear();
            ARS.Corners.Clear();
            ARS.Bumps.Clear();
            ARS.RouteLengthMeters = 0f;
            ARS.IsPointToPoint = false;
            ARS.CornersRevision++;
        }

        // The creator appends and deletes at the tail, so the *geometry* only needs rebuilding around the change —
        // every node-local read is within ten nodes. The apex table is rebuilt whole on purpose: its scan start is a
        // whole-route search, corners merge against the previous one, the table is cyclic on a circuit and the bump
        // seam spans the route, so no window of it is local. Both halves run the load pass's own rules.
        public static void RebuildRouteInfo(int firstChanged, int lastChanged)
        {
            bool wasPointToPoint = ARS.IsPointToPoint;
            RefreshRouteTopology();
            bool flipped = wasPointToPoint != ARS.IsPointToPoint;
            while (ARS.TrackPoints.Count > ARS.RouteNodes.Count) ARS.TrackPoints.RemoveAt(ARS.TrackPoints.Count - 1);
            while (ARS.TrackPoints.Count < ARS.RouteNodes.Count)
            {
                int node = ARS.TrackPoints.Count;
                ARS.TrackPoints.Add(new TrackPoint { Node = node, Position = ARS.RouteNodes[node] });
            }

            int count = ARS.RouteNodes.Count;
            long started = ARS.LogLevel <= ARS.LogImportance.Info ? System.Diagnostics.Stopwatch.GetTimestamp() : 0L;
            if (flipped)
            {
                // A flip moves every node between the two window laws, so nothing short of a full recompute is right.
                for (int node = 0; node < count; node++) ComputePointGeometry(ARS.TrackPoints[node], count);
            }
            else
            {
                int from = Math.Max(0, firstChanged - GeometryWindowNodes);
                int to = Math.Min(count - 1, lastChanged + GeometryWindowNodes);
                if (to < from) to = from;
                for (int node = from; node <= to && node < count; node++) ComputePointGeometry(ARS.TrackPoints[node], count);

                if (!ARS.IsPointToPoint)
                {
                    // A circuit wraps, so a change at the tail also moves the head, which reads across the seam.
                    for (int node = 0; node <= GeometryWindowNodes && node < count; node++) ComputePointGeometry(ARS.TrackPoints[node], count);
                }
                else
                {
                    // The band's boundary is the count minus a constant, so any change moves it: both bands are
                    // invalidated by an append or a delete, wherever it lands.
                    for (int node = 0; node <= PointToPointEndBandNodes && node < count; node++) ComputePointGeometry(ARS.TrackPoints[node], count);
                    for (int node = Math.Max(0, count - 1 - PointToPointEndBandNodes); node < count; node++) ComputePointGeometry(ARS.TrackPoints[node], count);
                }
            }

            RecomputeCumulativeDistances();
            BuildApexTable();
            if (ARS.LogLevel <= ARS.LogImportance.Info) LogRebuildAndVerify(started);
        }

        // Test-only, and gated *before* any work is prepared: Log cannot suppress its own arguments, so the check
        // returns early rather than being wrapped around a call. It times the local rebuild that just ran and then
        // re-runs the load pass over the same route, so the incremental table is proved against the reference.
        static void LogRebuildAndVerify(long started)
        {
            long localMs = (System.Diagnostics.Stopwatch.GetTimestamp() - started) * 1000L / System.Diagnostics.Stopwatch.Frequency;
            string incremental = CornerSignature();
            System.Diagnostics.Stopwatch watch = System.Diagnostics.Stopwatch.StartNew();
            GenerateRouteInfo();
            watch.Stop();
            string full = CornerSignature();
            ARS.Log(ARS.LogImportance.Info, "Route rebuild: " + (incremental == full ? "incremental matches the full pass" : "INCREMENTAL DIFFERS from the full pass")
                + " (" + ARS.RouteNodes.Count + " nodes, local " + localMs + "ms, full " + watch.ElapsedMilliseconds + "ms)"
                + (incremental == full ? "" : "\n  incremental " + incremental + "\n  full        " + full));
        }

        static string CornerSignature()
        {
            System.Text.StringBuilder text = new System.Text.StringBuilder();
            text.Append("bumps=").Append(ARS.Bumps.Count);
            foreach (Bump bump in ARS.Bumps)
            {
                text.Append(" b").Append(bump.LipNode).Append(',').Append(bump.RiseStartNode)
                    .Append(',').Append(bump.DepartureGrade.ToString("0.###", CultureInfo.InvariantCulture));
            }
            foreach (CornerPoint corner in ARS.Corners)
            {
                text.Append(" | ").Append(corner.Node).Append(':').Append(corner.StartNode).Append('-').Append(corner.EndNode)
                    .Append('@').Append(corner.Angle.ToString("0.###", CultureInfo.InvariantCulture))
                    .Append('x').Append(corner.Speed.ToString("0.##", CultureInfo.InvariantCulture))
                    .Append('l').Append(corner.LengthStart).Append(',').Append(corner.LengthEnd)
                    .Append(corner.IsChicane ? "C" : "c")
                    .Append('/').Append(corner.SupposedRadius.ToString("0.##", CultureInfo.InvariantCulture))
                    .Append('/').Append(corner.DetectedRadius.ToString("0.##", CultureInfo.InvariantCulture));
            }
            return text.ToString();
        }

        public static void BuildApexTable()
        {
            ARS.Corners.Clear();
            int count = ARS.TrackPoints.Count;
            if (count < 1) return;

            const float regionRadius = 200f;
            const int smoothingNodes = 2;
            const int exitRelaxationNodes = 4;
            const int minimumCornerNodes = 25;
            const float closeCornerSeconds = 2f;

            // Start a circuit scan on a straight so a corner crossing the node-zero boundary
            // is detected as one region rather than split between the end and beginning.
            int scanStart = 0;
            if (!ARS.IsPointToPoint)
            {
                for (int node = 0; node < count; node++)
                {
                    if (SmoothedRadius(node, count, smoothingNodes) >= regionRadius)
                    {
                        scanStart = node;
                        break;
                    }
                }
            }

            List<int> scanNodes = new List<int>(count);
            for (int offset = 0; offset < count; offset++)
            {
                int node = ARS.IsPointToPoint
                    ? scanStart + offset
                    : Wrap(scanStart + offset, count);
                if (node >= 0 && node < count) scanNodes.Add(node);
            }

            bool inCorner = false;
            int cornerStartPosition = -1;
            int cornerDirection = 0;
            int relaxedNodes = 0;

            for (int position = 0; position < scanNodes.Count; position++)
            {
                int node = scanNodes[position];
                float radius = SmoothedRadius(node, count, smoothingNodes);
                float generalRadius = ARS.TrackPoints[node].GeneralCurveRadius;
                int direction = Math.Sign(ARS.TrackPoints[node].Angle);
                bool cornerSignal = radius < regionRadius && generalRadius < regionRadius;

                if (!inCorner)
                {
                    if (cornerSignal && direction != 0)
                    {
                        inCorner = true;
                        cornerStartPosition = position;
                        cornerDirection = direction;
                        relaxedNodes = 0;
                    }
                    continue;
                }

                if (direction != 0 && direction != cornerDirection && cornerSignal)
                {
                    AddCornerRegion(scanNodes, cornerStartPosition, position - 1, count, smoothingNodes, minimumCornerNodes, closeCornerSeconds);
                    cornerStartPosition = position;
                    cornerDirection = direction;
                    relaxedNodes = 0;
                    continue;
                }

                if (!cornerSignal || direction == 0)
                    relaxedNodes++;
                else
                    relaxedNodes = 0;

                if (relaxedNodes >= exitRelaxationNodes)
                {
                    AddCornerRegion(scanNodes, cornerStartPosition, position - relaxedNodes, count, smoothingNodes, minimumCornerNodes, closeCornerSeconds);
                    inCorner = false;
                    cornerStartPosition = -1;
                    cornerDirection = 0;
                    relaxedNodes = 0;
                }
            }

            if (inCorner)
                AddCornerRegion(scanNodes, cornerStartPosition, scanNodes.Count - 1, count, smoothingNodes, minimumCornerNodes, closeCornerSeconds);

            float widestApexRadius = 0f;
            foreach (CornerPoint counted in ARS.Corners) widestApexRadius = Math.Max(widestApexRadius, counted.SupposedRadius);
            ARS.Log(ARS.LogImportance.Info, "Apex table: " + ARS.Corners.Count + " corners, widest apex radius " + widestApexRadius.ToString("0") + "m");

            // A chicane turns the heading back on itself, so the headings either side of the apex lie on the same
            // side of the apex direction and the signed angles match. A single corner keeps turning, so they differ.
            int nodeCount = ARS.TrackPoints.Count;
            for (int i = 0; i < ARS.Corners.Count; i++)
            {
                CornerPoint corner = ARS.Corners[i];
                int apex = corner.Node;
                int walkDist = (int)(ARS.TrackPoints[apex].TrackHalfWidth * 4f); // full width × 2
                Vector3 apexDir = ARS.TrackPoints[apex].Direction;

                int backNode = apex - walkDist;
                if (!ARS.IsPointToPoint) backNode = ((backNode % nodeCount) + nodeCount) % nodeCount;
                if (backNode < 0 || backNode >= nodeCount) continue;

                int fwdNode = apex + walkDist;
                if (!ARS.IsPointToPoint) fwdNode = fwdNode % nodeCount;
                if (fwdNode < 0 || fwdNode >= nodeCount) continue;

                float angleBack = Vector3.SignedAngle(apexDir, ARS.TrackPoints[backNode].Direction, Vector3.WorldUp);
                float angleFwd = Vector3.SignedAngle(apexDir, ARS.TrackPoints[fwdNode].Direction, Vector3.WorldUp);

                if (Math.Abs(angleBack) > 1f && Math.Abs(angleFwd) > 1f && Math.Sign(angleBack) == Math.Sign(angleFwd))
                {
                    corner.IsChicane = true;
                }
            }

            AssignCrests(nodeCount);
            AssignBumpNodes(nodeCount);

            ARS.CornersRevision++;
        }

        const float BumpDepartureRungMeters = 2f;
        const float BumpOnsetRungMeters = 3f;
        const float BumpMinRunMeters = 2f;
        const float BumpMaxRunMeters = 8f;
        const float BumpMinDepartureGrade = 0.03f;
        const float BumpMinLipDrop = 0.02f;
        // A seam is distrusted as soon as it is steep enough to nominate a lip on its own.
        const float BumpSeamMaxGrade = BumpMinDepartureGrade;
        // A compared grade on a three-metre rung carries about 0.007 of rounding error at worst, so this drop clears it,
        // and a second sample that fails to fall ends the run so a lone noise uptick cannot.
        const float BumpRiseGradeDrop = 0.01f;

        // A bump is a short convex break in the route where a car at speed goes light: the road may drop away after it
        // or only ease, and either way the curvature launches the car. The run lengths it reports are node-quantised,
        // so a coarse track resolves them to half a node. Scanned on the route line only; the raycast that reads the
        // real surface, and the lane-local case with it, come later.
        static void AssignBumpNodes(int count)
        {
            ARS.Bumps.Clear();
            if (count < 8) return;

            // The route's first and last nodes are one edge apart, and where that edge steps in height the difference
            // reads as grade. A broken seam therefore takes no lip within a run's length of it.
            bool seamOk = true;
            float seamGrade = 0f;
            if (!ARS.IsPointToPoint)
            {
                int across = NodeAhead(count - 1, 1f, count);
                float seamRun = HorizontalDistance(ARS.TrackPoints[count - 1].Position, ARS.TrackPoints[across].Position);
                seamGrade = seamRun > 0.01f ? Math.Abs(ARS.TrackPoints[across].Position.Z - ARS.TrackPoints[count - 1].Position.Z) / seamRun : 0f;
                seamOk = seamGrade <= BumpSeamMaxGrade;
            }
            int seamEnd = seamOk ? -1 : NodeAhead(0, BumpMaxRunMeters, count);
            int seamStart = seamOk ? count : NodeBehind(count - 1, BumpMaxRunMeters, count);

            for (int node = 0; node < count; node++)
            {
                if (!seamOk && (node <= seamEnd || node >= seamStart)) continue;

                float grade = GradeAt(node, BumpDepartureRungMeters, count);
                if (grade < BumpMinDepartureGrade) continue;

                int after = NodeAhead(node, BumpOnsetRungMeters, count);
                float drop = grade - GradeAt(after, BumpDepartureRungMeters, count);
                if (drop < BumpMinLipDrop) continue;

                int riseStart = RiseStartNode(node, count, out float riseMeters);
                if (riseStart < 0 || riseMeters < BumpMinRunMeters) continue;

                int before = NodeBehind(node, BumpDepartureRungMeters, count);
                float run = HorizontalDistance(ARS.TrackPoints[before].Position, ARS.TrackPoints[node].Position);
                float departure = run > 0.01f ? (ARS.TrackPoints[node].Position.Z - ARS.TrackPoints[before].Position.Z) / run : 0f;

                ARS.Bumps.Add(new Bump
                {
                    LipNode = node,
                    RiseStartNode = riseStart,
                    DepartureGrade = departure,
                    LipCurvature = drop / BumpOnsetRungMeters,
                });

                if (after > node) node = after;
            }

            foreach (Bump bump in ARS.Bumps)
                ARS.Log(ARS.LogImportance.Info, "Bump: lip=" + bump.LipNode + " rise=" + bump.RiseStartNode + " grade=" + bump.DepartureGrade.ToString("0.000") + " curvature=" + bump.LipCurvature.ToString("0.000"));

            if (!seamOk) ARS.Log(ARS.LogImportance.Info, "Bumps: the route seam steps at grade " + seamGrade.ToString("0.000") + ", so no lip is taken within " + BumpMaxRunMeters.ToString("0.0") + "m of it");
            ARS.Log(ARS.LogImportance.Info, "Bumps: " + ARS.Bumps.Count + " lips, minimum departure grade " + BumpMinDepartureGrade.ToString("0.000") + ", run " + BumpMinRunMeters.ToString("0.0") + "-" + BumpMaxRunMeters.ToString("0.0") + "m");
        }

        // Walks back from the lip while the surface is still climbing, so the run it returns is the rise itself. The
        // base is where the grade stops falling, read on the longer rung because a shorter one is too noisy to compare,
        // and one sample that fails to fall is passed over as noise. A climb longer than the cap is a slope, not a
        // bump, and reports -1.
        static int RiseStartNode(int lip, int count, out float meters)
        {
            meters = 0f;
            int node = lip;
            int start = lip;
            int flat = 0;
            float grade = GradeAt(lip, BumpOnsetRungMeters, count);
            for (int step = 0; step < 60; step++)
            {
                int behind = NodeBehind(node, 1f, count);
                if (behind == node) break;
                float behindGrade = GradeAt(behind, BumpOnsetRungMeters, count);
                if (behindGrade <= 0f) break;
                if (behindGrade > grade - BumpRiseGradeDrop)
                {
                    flat++;
                    if (flat >= 2) break;
                }
                else flat = 0;
                meters += HorizontalDistance(ARS.TrackPoints[behind].Position, ARS.TrackPoints[node].Position);
                node = behind;
                start = behind;
                grade = behindGrade;
                if (meters >= BumpMaxRunMeters) break;
            }
            if (meters >= BumpMaxRunMeters) return -1;
            return start;
        }

        static float GradeAt(int node, float rungMeters, int count)
        {
            int ahead = NodeAhead(node, rungMeters * 0.5f, count);
            int behind = NodeBehind(node, rungMeters * 0.5f, count);
            float run = HorizontalDistance(ARS.TrackPoints[behind].Position, ARS.TrackPoints[ahead].Position);
            if (run <= 0.01f) return 0f;
            return (ARS.TrackPoints[ahead].Position.Z - ARS.TrackPoints[behind].Position.Z) / run;
        }

        static int NodeAhead(int from, float meters, int count)
        {
            int node = from;
            float walked = 0f;
            for (int step = 0; step < 200 && walked < meters; step++)
            {
                if (!TryResolveNode(node + 1, count, out int next)) break;
                walked += HorizontalDistance(ARS.TrackPoints[node].Position, ARS.TrackPoints[next].Position);
                node = next;
            }
            return node;
        }

        static int NodeBehind(int from, float meters, int count)
        {
            int node = from;
            float walked = 0f;
            for (int step = 0; step < 200 && walked < meters; step++)
            {
                if (!TryResolveNode(node - 1, count, out int previous)) break;
                walked += HorizontalDistance(ARS.TrackPoints[node].Position, ARS.TrackPoints[previous].Position);
                node = previous;
            }
            return node;
        }

        static float HorizontalDistance(Vector3 a, Vector3 b)
        {
            float dx = a.X - b.X;
            float dy = a.Y - b.Y;
            return (float)Math.Sqrt(dx * dx + dy * dy);
        }

        // A crest before a corner unloads the tyres exactly where the car wants to brake, so the braking plan must know
        // about it and the entrance moves back to its top. Scanned once here, after the merges, because every rule that
        // rewrites the entrance has to have settled first. The scan is deliberately boundary-free: a crest that belongs
        // Route-wide scan for crests and dips. The scanner advances in fixed 20-node chunks: in each chunk it finds
        // the strongest |Gs| peak (largest magnitude, ties broken by first), writes the feature's entry/exit at
        // the half-peak-gs threshold on each side, then jumps to exit + 1. A long climb with bumps every few
        // nodes therefore produces one crest per 20-node window instead of one per node -- no overlap, no
        // re-checking. The half-gs rule on each side is unchanged from the per-node scan.
        //
        // Per-peak speed sweep: a feature's activation speed is the lowest m/s at which its curvature
        // still produces |gs| >= threshold. A feature that only activates at 80 m/s is invisible to a
        // 30 m/s car; one that activates at 25 m/s is a real low-speed crest. The chunked scan finds
        // candidate peaks at scanSpeed (a high anchor so anything that *can* be a crest gets picked),
        // then each peak's activation speed is refined by a per-peak decreasing sweep.
        //
        // Hard cap of 60 nodes in each direction from the peak: a feature whose half-gs walk never closes (flat
        // road, no sign flip) was unbounded and could pin a position forever; the cap mirrors the user's
        // intent that the entry/exit live close to the peak. The scanner's outer advance is also bounded: any
        // single chunk iteration that produces no usable feature still advances by at least one node.
        static void AssignCrests(int count)
        {
            const float threshold = 0.50f;
            const int window = 6;
            const int scanBack = 100;
            const int minRun = 3;
            const int chunkSize = 2;
            const int halfSpanCap = 60;
            const float scanSpeed = 90f;            // 200 mph, the high anchor; anything not a crest here isn't one at all
            const float speedStep = 2f;             // 2 m/s steps; activation speed has ~2 m/s precision
            const float minActivationSpeed = 5f;    // a feature that doesn't crest above 5 m/s is too slow to matter
            const float entryExitGs = 0.05f;        // absolute |gs| where the half-gs walk stops; flat-ground boundary
            const int minFeatureSpanNodes = 20;     // a real crest/dip has a wide flatness extent; sharp lips close in <20 nodes

            ARS.Crests.Clear();
            // The outer 'while (node < count)' is wrong on a circuit: 'node = Wrap(node + 1, count)' cycles
            // through [0, count) forever on a flat road. Track which nodes have been visited and stop when
            // the next 'node' has already been seen. On a point-to-point track the guard fires only on a
            // real revisit, which never happens with the current advances.
            bool[] visited = new bool[count];
            int node = 0;
            while (node < count)
            {
                if (visited[node]) break;
                visited[node] = true;
                int bestNode = -1;
                float bestGs = 0f;
                // For circuit wraps the chunk crosses zero; iterate up to chunkSize nodes starting at 'node',
                // wrapping at 'count' so the inner loop never runs past 'node + chunkSize' in node-space.
                // The peak finder runs at scanSpeed (the high anchor) so any feature that *can* be a crest
                // at any speed is captured here. The per-peak activation-speed sweep refines the actual gs.
                for (int step = 0; step < chunkSize; step++)
                {
                    int i = ARS.IsPointToPoint ? node + step : Wrap(node + step, count);
                    if (i >= count) break;
                    if (!TryResolveNode(i - window, count, out int before)) continue;
                    if (!TryResolveNode(i, count, out int centre)) continue;
                    if (!TryResolveNode(i + window, count, out int after)) continue;
                    float g = ARS.HillGripDeltaGs(ARS.TrackPoints[before].Position, ARS.TrackPoints[centre].Position, ARS.TrackPoints[after].Position, scanSpeed);
                    if (Math.Abs(g) < threshold) continue;
                    if (Math.Abs(g) <= Math.Abs(bestGs)) continue;
                    bestGs = g;
                    bestNode = i;
                }

                if (bestNode < 0)
                {
                    // No peak in this chunk; advance by one node so we keep making progress.
                    node = ARS.IsPointToPoint ? node + 1 : Wrap(node + 1, count);
                    continue;
                }

                CrestType type = bestGs < 0f ? CrestType.Crest : CrestType.Dip;
                int sign = bestGs < 0f ? -1 : 1;
                int peakNode = bestNode;
                float peakGs = bestGs;

                // Per-peak activation-speed sweep. Start at scanSpeed (where bestGs was just measured),
                // step down by speedStep until |gs| drops below threshold. The activation speed is the
                // last speed still above threshold -- the lowest speed at which this feature still
                // classifies as a crest or dip. A feature that doesn't crest above minActivationSpeed
                // is road noise at any speed the car can carry; drop it.
                float activationSpeed = scanSpeed;
                if (!TryResolveNode(peakNode - window, count, out int peakBefore) ||
                    !TryResolveNode(peakNode, count, out int peakCentre) ||
                    !TryResolveNode(peakNode + window, count, out int peakAfter))
                {
                    node = ARS.IsPointToPoint ? node + 1 : Wrap(node + 1, count);
                    continue;
                }
                bool activationFound = false;
                for (float s = scanSpeed; s >= minActivationSpeed; s -= speedStep)
                {
                    float gAtS = ARS.HillGripDeltaGs(ARS.TrackPoints[peakBefore].Position, ARS.TrackPoints[peakCentre].Position, ARS.TrackPoints[peakAfter].Position, s);
                    if (Math.Sign(gAtS) != sign) continue;       // a sign flip in the sweep is a different feature, not this one
                    if (Math.Abs(gAtS) < threshold)
                    {
                        // The previous step was the last speed that still produced |gs| >= threshold.
                        activationFound = true;
                        break;
                    }
                    activationSpeed = s;
                }
                if (!activationFound || activationSpeed < minActivationSpeed)
                {
                    node = ARS.IsPointToPoint ? node + 1 : Wrap(node + 1, count);
                    continue;
                }
                // The half-gs walks use the activation speed so the entry/exit live at the gs values
                // the car actually experiences. peakGs is re-measured at activation speed: a feature
                // whose gs grows quadratically with v would have a much higher peak at scanSpeed than
                // at the speed the car actually crosses it.
                peakGs = ARS.HillGripDeltaGs(ARS.TrackPoints[peakBefore].Position, ARS.TrackPoints[peakCentre].Position, ARS.TrackPoints[peakAfter].Position, activationSpeed);

                // Walk backwards until |Gs| has fallen to entryExitGs (0.05g, an absolute flatness
                // threshold) or a sign flip, or halfSpanCap nodes have passed. The absolute threshold
                // is independent of peak strength, so a 0.2g peak and a 0.8g peak both stop walking
                // at the same flat-ground boundary -- two close features' exits no longer cross each
                // other's entries, and a low-strength peak's entry sits close to its peak rather than
                // out on the slope.
                int entry = peakNode;
                bool entryClosed = false;
                for (int back = 1; back <= halfSpanCap; back++)
                {
                    if (!TryResolveNode(peakNode - back, count, out int b)) break;
                    if (!TryResolveNode(peakNode - back - window, count, out int bb)) break;
                    if (!TryResolveNode(peakNode - back + window, count, out int ba)) break;
                    float g2 = ARS.HillGripDeltaGs(ARS.TrackPoints[bb].Position, ARS.TrackPoints[b].Position, ARS.TrackPoints[ba].Position, activationSpeed);
                    if (Math.Sign(g2) != sign || Math.Abs(g2) <= entryExitGs)
                    {
                        entry = ARS.IsPointToPoint ? peakNode - (back - 1) : Wrap(peakNode - (back - 1), count);
                        entryClosed = true;
                        break;
                    }
                }
                // Walk forward until |Gs| has fallen to entryExitGs or a sign flip, or halfSpanCap nodes.
                int exit = peakNode;
                bool exitClosed = false;
                for (int fwd = 1; fwd <= halfSpanCap; fwd++)
                {
                    if (!TryResolveNode(peakNode + fwd, count, out int f)) break;
                    if (!TryResolveNode(peakNode + fwd - window, count, out int ff)) break;
                    if (!TryResolveNode(peakNode + fwd + window, count, out int fa)) break;
                    float g3 = ARS.HillGripDeltaGs(ARS.TrackPoints[ff].Position, ARS.TrackPoints[f].Position, ARS.TrackPoints[fa].Position, activationSpeed);
                    if (Math.Sign(g3) != sign || Math.Abs(g3) <= entryExitGs)
                    {
                        exit = ARS.IsPointToPoint ? peakNode + (fwd - 1) : Wrap(peakNode + (fwd - 1), count);
                        exitClosed = true;
                        break;
                    }
                }

                // Drop the feature if either half-gs walk never closed: the road never came back to flat
                // within halfSpanCap, so the scanner is reading noise rather than a closed shape. The default
                // 60-node entry/exit can otherwise wrap the seam on a short circuit and produce a 120-node
                // feature whose entry sits past its exit in drive-order.
                if (!entryClosed || !exitClosed) { node = Wrap(peakNode + 1, count); continue; }

                // Skip features shorter than the run threshold -- a single noisy node.
                if (ARS.IsPointToPoint)
                {
                    if (exit - peakNode < minRun || peakNode - entry < minRun) { node = Math.Min(peakNode + 1, count); continue; }
                }
                else
                {
                    int entryRun = Wrap(peakNode - entry, count);
                    int exitRun = Wrap(exit - peakNode, count);
                    if (exitRun < minRun || entryRun < minRun) { node = Wrap(peakNode + 1, count); continue; }
                }
                // A real crest or dip has a wide flatness extent: the curvature rolls up over many nodes
                // and back down. A sharp lip or jump has gs that drops from 1g+ to 0.05g in 1-3 nodes,
                // which closes the half-gs walk too soon and produces a tiny spurious feature. The
                // minFeatureSpanNodes gate drops both crests and dips that close faster than this -- the
                // 0.05g absolute threshold can be reached by a single curved-edge transition; the 20-node
                // span is what separates a true rolling crest from a lifting lip.
                if (ARS.IsPointToPoint)
                {
                    if (exit - peakNode < minFeatureSpanNodes || peakNode - entry < minFeatureSpanNodes) { node = Math.Min(peakNode + 1, count); continue; }
                }
                else
                {
                    int entrySpan = Wrap(peakNode - entry, count);
                    int exitSpan = Wrap(exit - peakNode, count);
                    if (exitSpan < minFeatureSpanNodes || entrySpan < minFeatureSpanNodes) { node = Wrap(peakNode + 1, count); continue; }
                }

                Crest feature = new Crest
                {
                    Node = peakNode,
                    EntryNode = entry,
                    ExitNode = exit,
                    PeakGs = peakGs,
                    Type = type,
                    ActivationSpeed = activationSpeed
                };
                ARS.Crests.Add(feature);

                // Advance past the exit so the next chunk starts after this feature.
                int next = ARS.IsPointToPoint ? exit + 1 : Wrap(exit + 1, count);
                if (next == node) { node = Wrap(node + 1, count); continue; }     // a stuck exit can't make progress; force one node
                node = next;
            }

            int crests = 0, dips = 0;
            foreach (Crest c in ARS.Crests)
            {
                if (c.Type == CrestType.Crest) crests++; else dips++;
                ARS.Log(ARS.LogImportance.Info, (c.Type == CrestType.Crest ? "Crest" : "Dip") + " peak=" + c.Node + " entry=" + c.EntryNode + " exit=" + c.ExitNode + " gs=" + c.PeakGs.ToString("0.000") + " act=" + c.ActivationSpeed.ToString("0") + "m/s extent=" + (c.ExitNode - c.Node) + "+" + (c.Node - c.EntryNode));
            }
            ARS.Log(ARS.LogImportance.Info, "Features: " + crests + " crests, " + dips + " dips, threshold " + threshold.ToString("0.00") + "g, entryExit=" + entryExitGs.ToString("0.00") + "g, scanSpeed=" + scanSpeed.ToString("0") + "m/s, chunk=" + chunkSize + " nodes, halfSpan=" + halfSpanCap + " nodes");
        }

        static bool TryResolveNode(int node, int count, out int resolved)
        {
            resolved = 0;
            if (ARS.IsPointToPoint)
            {
                if (node < 0 || node >= count) return false;
                resolved = node;
                return true;
            }
            resolved = Wrap(node, count);
            return true;
        }

        static void AddCornerRegion(List<int> scanNodes, int startPosition, int endPosition, int count, int smoothingNodes, int minimumCornerNodes, float closeCornerSeconds)
        {
            if (startPosition < 0 || endPosition < startPosition || endPosition - startPosition + 1 < minimumCornerNodes)
                return;

            int regionStart = startPosition;
            int regionEnd = endPosition;

            int apexPosition = startPosition;
            float tightestRadius = float.MaxValue;
            float detectedRadius = float.MaxValue;
            for (int position = startPosition; position <= endPosition; position++)
            {
                float radius = ARS.TrackPoints[scanNodes[position]].PreciseCurveRadius;
                if (radius < tightestRadius) tightestRadius = radius;
                // The apex is the smoothed minimum, not the tightest node: the precise radius is a three-point
                // circumradius over the node and its +/-4-node samples, so on a wide corner its noise sits at the
                // file's decimal quantum and the tightest node lands tens of metres off the real apex.
                float smoothed = SmoothedRadius(scanNodes[position], count, smoothingNodes);
                if (smoothed < detectedRadius)
                {
                    detectedRadius = smoothed;
                    apexPosition = position;
                }
            }

            if (float.IsNaN(tightestRadius) || float.IsInfinity(tightestRadius)) return;
            // A wide region is a bend, not a corner: the tightest node reads the precise radius, which the region's
            // smoothed radius can sit well under, so a region does open without a tight node inside it.
            if (tightestRadius > MaximumApexRadius) return;

            int apexNode = scanNodes[apexPosition];
            // A span is capped at a hard node count each way rather than by the corner's own size: offroad the radius
            // never settles, so without a cap the walk runs all the way out to the region bound. The step is also capped
            // by what the scan list holds, because the walk returns a step count and these are list positions.
            int spanLimit = Math.Min(SpanNodeLimit, count - 1);
            int entranceMaxStep = Math.Min(spanLimit, apexPosition);
            int exitMaxStep = Math.Min(spanLimit, scanNodes.Count - 1 - apexPosition);
            int entranceStep = EntranceStep(apexNode, tightestRadius, entranceMaxStep, count);
            int exitStep = ExitStep(apexNode, tightestRadius, exitMaxStep, count);
            int unclampedStart = apexPosition - entranceStep;
            int unclampedEnd = apexPosition + exitStep;
            startPosition = Math.Max(regionStart, unclampedStart);
            endPosition = Math.Min(regionEnd, unclampedEnd);
            // Diagnostic: log every corner's region bounds, walk direction, and where the clamping actually happens.
            // The user observed that one corner's entrance lands at regionStart regardless of the multiple — confirm.
            ARS.Log(ARS.LogImportance.Info, "Corner add: apex=" + apexNode + " angle=" + ARS.TrackPoints[apexNode].Angle.ToString("0.0") + " tightestR=" + tightestRadius.ToString("0.0") + " region=" + regionStart + "-" + regionEnd + " entranceStep=" + entranceStep + "/" + entranceMaxStep + (entranceStep >= entranceMaxStep ? " (at cap)" : "") + " unclampedStart=" + unclampedStart + " start=" + startPosition + (startPosition > unclampedStart ? " (clamped to regionStart)" : (startPosition == unclampedStart ? " (walk stop)" : "")) + " exitStep=" + exitStep + "/" + exitMaxStep + (exitStep >= exitMaxStep ? " (at cap)" : "") + " unclampedEnd=" + unclampedEnd + " end=" + endPosition);
            // Flat rather than the apex radius: scaling it gave a sweeper a span of twice its own radius, so the cars
            // prepared across the whole corner.
            float minEntranceExit = Math.Min(SpanMinimumMeters, spanLimit);
            // Rule 5 disabled while the cap is the user-facing rule: the floor pulled the entrance to 20m on
            // any corner where the walk returned a small step, which fought the cap and made the bound meaningless.
            // if (apexPosition - startPosition < minEntranceExit) startPosition = Math.Max(regionStart, apexPosition - (int)minEntranceExit);
            // if (endPosition - apexPosition < minEntranceExit) endPosition = Math.Min(regionEnd, apexPosition + (int)minEntranceExit);
            // Outer bound on entrance/exit distance from apex: the walk's uncapped step is hard-clamped at SpanMaxDistanceNodes,
            // regardless of region bounds or the multiple-based walk stop. If the cap binds, log a detailed line so the
            // road geometry that triggered it is visible.
            if (apexPosition - startPosition > SpanMaxDistanceNodes)
            {
                int priorStart = startPosition;
                startPosition = apexPosition - SpanMaxDistanceNodes;
                ARS.Log(ARS.LogImportance.Info, "Corner add CAP: apex=" + apexNode + " side=entrance priorStart=" + priorStart + " (distance=" + (apexPosition - priorStart) + ") clamped to start=" + startPosition + " (distance=" + (apexPosition - startPosition) + "); region=" + regionStart + "-" + regionEnd + " entranceStep=" + entranceStep + "/" + entranceMaxStep + (entranceStep >= entranceMaxStep ? " walkAtCap" : " walkStoppedEarly") + " unclampedStart=" + unclampedStart);
            }
            if (endPosition - apexPosition > SpanMaxDistanceNodes)
            {
                int priorEnd = endPosition;
                endPosition = apexPosition + SpanMaxDistanceNodes;
                ARS.Log(ARS.LogImportance.Info, "Corner add CAP: apex=" + apexNode + " side=exit priorEnd=" + priorEnd + " (distance=" + (priorEnd - apexPosition) + ") clamped to end=" + endPosition + " (distance=" + (endPosition - apexPosition) + "); region=" + regionStart + "-" + regionEnd + " exitStep=" + exitStep + "/" + exitMaxStep + (exitStep >= exitMaxStep ? " walkAtCap" : " walkStoppedEarly") + " unclampedEnd=" + unclampedEnd);
            }
            CornerPoint corner = new CornerPoint
            {
                Node = apexNode,
                Angle = ARS.TrackPoints[apexNode].Angle,
                StartNode = scanNodes[startPosition],
                EndNode = scanNodes[endPosition],
                LengthStart = apexPosition - startPosition,
                LengthEnd = endPosition - apexPosition,
                SupposedRadius = tightestRadius,
                DetectedRadius = detectedRadius,
                Speed = (float)Math.Sqrt(9.81f * tightestRadius)
            };

            // Coexistence is a question of time, not distance: the outside-approach window is a few seconds long, so
            // two apexes the car reaches within this many seconds fight over the same stretch. The table has no car
            // in it, so the corners' own 1 g apex speeds stand in — which is how the radius drives the decision.
            // Keeping the slower of the pair is deliberate, and it reads the smoothed radius because the survivor is
            // what every later consumer keys on. The survivor's extensions are then re-walked over the region it
            // absorbed: leaving them alone registers no corner where the car actually is.
            if (ARS.Corners.Count > 0)
            {
                CornerPoint previous = ARS.Corners[ARS.Corners.Count - 1];
                int gap = ARS.IsPointToPoint ? corner.Node - previous.Node : Wrap(corner.Node - previous.Node, count);
                float referenceSpeed = Math.Max(previous.Speed, corner.Speed);
                float gapSeconds = gap / Math.Max(referenceSpeed, 1f);
                // A fast kink seconds before a slow corner is one the car clears before it can react to the next: where
                // the two aim the same way there is no S to drive, so the slower apex should own the whole bend. The
                // window stays short of the time a U-turn's two apexes take to be planned separately, or the second
                // absorbs the first, and it stays under the gap two similar corners half a lap apart would show.
                bool sameBend = gapSeconds < AlignedCornerSeconds && AimsSameWay(previous, corner, AlignedCornerDegrees);
                if (gapSeconds < closeCornerSeconds || sameBend)
                {
                    // The radii differ by more than the gate: the two corners are unrelated bends, not the same
                    // bend with a kink. Skip the merge and drop the bigger-radius one -- the walker's walked
                    // bounds for the surviving smaller corner are kept, and the lost corner stays out of the list.
                    // 'fast corner followed by slow corner' -- drop the previous fast corner, keep the new slow one.
                    if (Math.Abs(corner.DetectedRadius - previous.DetectedRadius) > SpanMergeRadiusGate)
                    {
                        CornerPoint loser = corner.DetectedRadius < previous.DetectedRadius ? previous : corner;
                        bool dropPrevious = loser.Node == previous.Node;
                        ARS.Log(ARS.LogImportance.Info, "Corner skipped (radii differ by >" + SpanMergeRadiusGate.ToString("0") + "m): previousR=" + previous.DetectedRadius.ToString("0.0") + " cornerR=" + corner.DetectedRadius.ToString("0.0") + " loserApex=" + loser.Node + (dropPrevious ? " (previous)" : " (new)"));
                        // The smaller-radius corner wins. If the previous is the loser, drop it and add the new
                        // corner in its place; if the new is the loser, leave the previous as-is.
                        if (dropPrevious)
                        {
                            ARS.Corners.RemoveAt(ARS.Corners.Count - 1);
                            ARS.Corners.Add(corner);
                        }
                        return;
                    }
                    CornerPoint survivor = corner.DetectedRadius < previous.DetectedRadius ? corner : previous;
                    ExtendMergedCorner(survivor, previous.StartNode, corner.EndNode, count);
                    ARS.Corners[ARS.Corners.Count - 1] = survivor;
                    return;
                }
            }
            ARS.Corners.Add(corner);
        }

        // Whether one corner's exit aims where the next one's entrance aims: joined by a straight or a steady curve, so
        // the pair is really one bend rather than an S.
        static bool AimsSameWay(CornerPoint previous, CornerPoint corner, float degrees)
        {
            if (previous.EndNode < 0 || corner.StartNode < 0) return false;
            Vector3 exitDirection = ARS.TrackPoints[previous.EndNode].Direction;
            Vector3 entranceDirection = ARS.TrackPoints[corner.StartNode].Direction;
            float angle = Vector3.SignedAngle(exitDirection, entranceDirection, Vector3.WorldUp);
            return !float.IsNaN(angle) && !float.IsInfinity(angle) && Math.Abs(angle) <= degrees;
        }

        // A span end is where the road has held itself open for a stretch, so the entrance or exit cannot chatter
        // against a single noisy reading. The criterion is N consecutive PreciseCurveRadius values all above
        // multiple * SupposedRadius, with the walk step being the first one whose N consecutive ahead are open.
        // The walk is capped by the region the detector already found, because a corner whose approach is all
        // tighter than the multiple would otherwise run to the node cap.
        const int SpanConsecutiveNodes = 8;

        static int EntranceStep(int apexNode, float apexRadius, int maxStep, int count)
        {
            float threshold = apexRadius * SpanEntranceRadiusMultiple;
            for (int step = 1; step <= maxStep; step++)
            {
                if (IsOpenedFor(apexNode, -1, step, SpanConsecutiveNodes, count, threshold)) return step;
            }
            return maxStep;
        }

        const float SpanMinimumMeters = 20f;
        const float SpanEntranceRadiusMultiple = 1.5f;
        const float SpanExitRadiusMultiple = 1.5f;
        // Two apexes whose DetectedRadius differ by more than this are unrelated bends, not a kink in the same bend:
        // merging them drags the survivor's walked entrance to the looser corner's bound, which can produce an
        // entrance tens of nodes too far back on the apex the racer actually plans around. Skip the merge and drop
        // the bigger-radius corner instead.
        const float SpanMergeRadiusGate = 50f;
        const int SpanNodeLimit = 500;
        // Outer bound on how far from the apex an entrance or exit may land. The walk can otherwise run to its step
        // cap on long gentle approaches whose SmoothedRadius never opens past the multiple (a regime the b587cc5f
        // commit warned about), and the previous bound -- regionStart -- followed the detection sweep's tolerance,
        // which on Figureight reaches 100+ nodes. This cap is the user-facing rule: the entrance or exit cannot be
        // further than this many nodes from the apex; if the walk's unclamped step exceeds it, we clamp and log.
        const int SpanMaxDistanceNodes = 40;
        const float MaximumApexRadius = 200f;
        const float AlignedCornerSeconds = 3f;
        const float AlignedCornerDegrees = 15f;

        // The exit is the entrance's mirror, walked forward on the looser multiple.
        static int ExitStep(int apexNode, float apexRadius, int maxStep, int count)
        {
            float threshold = apexRadius * SpanExitRadiusMultiple;
            for (int step = 1; step <= maxStep; step++)
            {
                if (IsOpenedFor(apexNode, 1, step, SpanConsecutiveNodes, count, threshold)) return step;
            }
            return maxStep;
        }

        // True when N consecutive nodes from (apexNode + direction * step) onward (going the same direction) are
        // all above the threshold. The walk step is the first one where this holds, so the entrance or exit lands
        // where the road has held itself open rather than on a single noisy reading.
        static bool IsOpenedFor(int apexNode, int direction, int step, int consecutive, int count, float threshold)
        {
            for (int offset = 0; offset < consecutive; offset++)
            {
                int walk = step + offset;
                int node = ARS.IsPointToPoint
                    ? apexNode + direction * walk
                    : Wrap(apexNode + direction * walk, count);
                if (ARS.IsPointToPoint && (node < 0 || node >= count)) return false;
                if (ARS.TrackPoints[node].PreciseCurveRadius < threshold) return false;
            }
            return true;
        }

        // A merged survivor's extensions, re-walked rather than inherited: the entrance runs in over the absorbed
        // region to the same hard node limit a fresh region uses, and the exit is re-derived from the apex the
        // same way a fresh region's is, bounded by the absorbed region's end. The floor is capped by what is left of
        // each bound, so neither walk can pass it and a chain of merges stops at the first corner of the complex.
        // A survivor owns the whole bend it absorbed, so its span is the union of the two: the entrance reaches the
        // absorbed corner's entrance and the exit the new corner's exit, bounded only by the same hard node limit a
        // fresh region uses. The radius walk is deliberately not consulted — it reads around the survivor's own apex,
        // and since the survivor is usually the tighter corner its threshold is the smaller one, so a walk here could
        // cover less road than the two corners did separately and leave the first corner's braking zone unrecorded.
        static void ExtendMergedCorner(CornerPoint survivor, int unionStart, int unionEnd, int count)
        {
            int spanLimit = Math.Min(SpanNodeLimit, count - 1);
            int entranceDistance = Math.Min(ARS.IsPointToPoint ? survivor.Node - unionStart : Wrap(survivor.Node - unionStart, count), spanLimit);
            int exitDistance = Math.Min(ARS.IsPointToPoint ? unionEnd - survivor.Node : Wrap(unionEnd - survivor.Node, count), spanLimit);
            survivor.StartNode = ARS.IsPointToPoint ? survivor.Node - entranceDistance : Wrap(survivor.Node - entranceDistance, count);
            survivor.EndNode = ARS.IsPointToPoint ? survivor.Node + exitDistance : Wrap(survivor.Node + exitDistance, count);
            survivor.LengthStart = entranceDistance;
            survivor.LengthEnd = exitDistance;
        }

        static float SmoothedRadius(int node, int count, int halfWindow)
        {
            float curvature = 0f;
            int samples = 0;
            for (int offset = -halfWindow; offset <= halfWindow; offset++)
            {
                int sample = ARS.IsPointToPoint
                    ? node + offset
                    : Wrap(node + offset, count);
                if (sample < 0 || sample >= count) continue;

                float radius = ARS.TrackPoints[sample].PreciseCurveRadius;
                if (radius <= 0f || radius >= 999f || float.IsNaN(radius) || float.IsInfinity(radius)) continue;
                curvature += 1f / radius;
                samples++;
            }

            return samples > 0 ? 1f / (curvature / samples) : 999f;
        }

        public static float Circumradius3D(Vector3 a, Vector3 b, Vector3 midpoint)
        {
            return Circumradius2D(new Vector2(a.X, a.Y), new Vector2(b.X, b.Y), new Vector2(midpoint.X, midpoint.Y));
        }

        public static float Circumradius2D(Vector2 a, Vector2 b, Vector2 midpoint)
        {
            Vector2 midpoint1 = (a + b) / 2;
            float dx1 = b.X - a.X;
            float slope1 = dx1 != 0f ? (b.Y - a.Y) / dx1 : float.PositiveInfinity;
            float perpendicular1 = slope1 != 0f ? -1 / slope1 : float.PositiveInfinity;
            Vector2 midpoint2 = (b + midpoint) / 2;
            float dx2 = midpoint.X - b.X;
            float slope2 = dx2 != 0f ? (midpoint.Y - b.Y) / dx2 : float.PositiveInfinity;
            float perpendicular2 = slope2 != 0f ? -1 / slope2 : float.PositiveInfinity;
            float denominator = perpendicular2 - perpendicular1;
            if (denominator == 0f || float.IsNaN(denominator) || float.IsInfinity(denominator)) return 999f;
            float centerX = (midpoint1.Y - midpoint2.Y + perpendicular2 * midpoint2.X - perpendicular1 * midpoint1.X) / denominator;
            float centerY = midpoint1.Y + perpendicular1 * (centerX - midpoint1.X);
            float radius = Vector2.Distance(new Vector2(centerX, centerY), a);
            return float.IsNaN(radius) || float.IsInfinity(radius) ? 999f : radius;
        }

        static int Wrap(int index, int count)
        {
            int wrapped = index % count;
            return wrapped < 0 ? wrapped + count : wrapped;
        }

        public static void BuildTrackLimits(List<Vector3> nodes, Dictionary<int, float> widths, XmlDocument trackFile, ref bool isPointToPoint, List<Prop> startFlares)
        {
            if (nodes.Count == 0) return;
            isPointToPoint |= nodes[0].DistanceTo(nodes[nodes.Count - 1]) > 20f;
            Color? flareColor = ReadFlareColor(trackFile);

            if (startFlares.Count == 0 && flareColor.HasValue) SpawnStartGates(nodes, widths, startFlares, flareColor.Value);
            Function.Call(Hash.CLEAR_FOCUS);
        }

        // Built to order rather than to a fixed ceiling: the grid needs slots for the size being spawned plus two
        // that GridBuilder.Place reads ahead into, and the size can change between spawns, so it is redone each time.
        public static void BuildGridSlots(List<Vector3> nodes, Dictionary<int, float> widths, bool isPointToPoint, int wantedCars, List<Vector3> grid)
        {
            grid.Clear();
            if (wantedCars <= 0) return;

            int slotCount = wantedCars + 2;
            if (isPointToPoint) BuildPointToPointGrid(nodes, widths, grid, slotCount);
            else BuildCircuitGrid(nodes, widths, grid, slotCount);
        }

        static void SpawnStartGates(List<Vector3> nodes, Dictionary<int, float> widths, List<Prop> limits, Color color)
        {
            // The line is the last node in both modes: a circuit wraps there and a point-to-point finishes across it.
            int last = nodes.Count - 1;
            SpawnGatePair(nodes[last], nodes[last] - nodes[Wrap(last - 1, nodes.Count)], widths.ContainsKey(last) ? widths[last] : widths[0], limits, color);
        }

        static void SpawnGatePair(Vector3 position, Vector3 direction, float width, List<Prop> limits, Color color)
        {
            // Offsets come from the direction, never from the prop's own right vector: that one is parallel to the track once its heading has been turned 90.
            Vector3 across = Quaternion.RotationAxis(Vector3.WorldUp, (float)Math.PI / 180f * -90f) * new Vector3(direction.X, direction.Y, 0f).Normalized;
            for (int side = -1; side <= 1; side += 2)
            {
                Prop gate = World.CreateProp("prop_flare_01b", position + across * width * side + new Vector3(0f, 0f, 0.05f), new Vector3(0, 0, direction.Normalized.ToHeading() + 90f), false, false);
                QueueFlare(gate, color);
                gate.FreezePosition = true;
                gate.HasCollision = false;
                limits.Add(gate);
            }
        }

        static void BuildPointToPointGrid(List<Vector3> nodes, Dictionary<int, float> widths, List<Vector3> grid, int slotCount)
        {
            for (int i = slotCount + 1; i > 1 && i * 3 < nodes.Count; i--)
            {
                Vector3 point = nodes[i * 3];
                Vector3 direction = (point - nodes[i * 3 - 1]).Normalized;
                grid.Add(point - Quaternion.RotationAxis(Vector3.WorldUp, (float)Math.PI / 180f * -90f) * (direction * ((i % 2 == 1) ? widths[0] * 0.45f : -widths[0] * 0.45f)));
            }
        }

        static void BuildCircuitGrid(List<Vector3> nodes, Dictionary<int, float> widths, List<Vector3> grid, int slotCount)
        {
            int reference = nodes.Count - 1;
            for (int i = nodes.Count - 1; i > 50 && grid.Count < slotCount; i--)
            {
                if (i >= reference - 5) continue;
                Vector3 direction = (nodes[reference] - nodes[i]).Normalized;
                grid.Add(nodes[i] - Quaternion.RotationAxis(Vector3.WorldUp, (float)Math.PI / 180f * -90f) * (direction * ((grid.Count % 2 == 1) ? -widths[0] * 0.45f : widths[0] * 0.45f)));
                reference = i;
            }
        }

        static Color? ReadFlareColor(XmlDocument trackFile)
        {
            string value = trackFile?.SelectSingleNode("//Trackside") is XmlElement element ? element.GetAttribute("Flares") : "";
            if (value == "false") return null;
            int rgb;
            return value.Length == 9 && int.TryParse(value, out rgb) ? Color.FromArgb(int.Parse(value.Substring(0, 3)), int.Parse(value.Substring(3, 3)), int.Parse(value.Substring(6, 3))) : Color.GreenYellow;
        }

        const string FlarePtfxAsset = "scr_apartment_mp";
        const string FlarePtfxEffect = "scr_finders_package_flare";
        static readonly List<KeyValuePair<Prop, Color>> QueuedFlares = new List<KeyValuePair<Prop, Color>>();

        // A named ptfx asset streams over frames, so the effect cannot start in the same tick it is requested.
        static void QueueFlare(Prop prop, Color color)
        {
            QueuedFlares.Add(new KeyValuePair<Prop, Color>(prop, color));
        }

        public static void TickQueuedFlares(List<int> effects)
        {
            if (QueuedFlares.Count == 0) return;
            if (!Function.Call<bool>(Hash.HAS_NAMED_PTFX_ASSET_LOADED, FlarePtfxAsset))
            {
                Function.Call(Hash.REQUEST_NAMED_PTFX_ASSET, FlarePtfxAsset);
                return;
            }

            for (int i = QueuedFlares.Count - 1; i >= 0; i--)
            {
                Prop prop = QueuedFlares[i].Key;
                Color color = QueuedFlares[i].Value;
                QueuedFlares.RemoveAt(i);
                if (!ARS.CanWeUse(prop)) continue;

                Function.Call(Hash._SET_PTFX_ASSET_NEXT_CALL, FlarePtfxAsset);
                int effect = Function.Call<int>(Hash.START_PARTICLE_FX_LOOPED_ON_ENTITY, FlarePtfxEffect, prop, 0f, 0f, 0.1f, 0f, 0f, 0f, 1f, true, true, true);
                if (effect == 0)
                {
                    ARS.Log(ARS.LogImportance.Info, "Flare: " + FlarePtfxEffect + " did not start from " + FlarePtfxAsset);
                    continue;
                }
                Function.Call(Hash.SET_PARTICLE_FX_LOOPED_ALPHA, effect, 1f);
                Function.Call(Hash.SET_PARTICLE_FX_LOOPED_COLOUR, effect, color.R / 255f, color.G / 255f, color.B / 255f, 1f, true);
                effects.Add(effect);
            }
        }
